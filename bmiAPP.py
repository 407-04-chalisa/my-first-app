import streamlit as st

# ส่วนที่ 1 หัวข้อหน้าเว็บ
st.markdown("# :pink[🏋️ แอปพลิเคชันคำนวณค่าดัชนีมวลกาย BMI]")
st.write("กรอกข้อมูลน้ำหนักและส่วนสูงของคุณ เพื่อเช็กสุขภาพเบื้องต้น")

# ส่วนที่ 2 ช่องรับค่าน้ำหนักและส่วนสูง (ใส่ min_value เพื่อป้องกันค่า 0)
weight = st.number_input("กรอกน้ำหนักของคุณ (กิโลกรัม):", min_value=1.0, value=60.0, step=0.5)
height_cm = st.number_input("กรอกส่วนสูงของคุณ (เซนติเมตร):", min_value=1.0, value=165.0, step=1.0)

# ส่วนที่ 3 สร้างปุ่มกดคำนวณ
if st.button("คำนวณค่า BMI 🎯"):
    if height_cm > 0:
        # แปลงส่วนสูงจาก cm เป็น เมตร แล้วคำนวณ BMI
        height_m = height_cm / 100
        bmi = weight / (height_m ** 2)

        st.write("---")
        st.header(f"ค่า BMI ของคุณคือ: **{bmi:.2f}**")

        # ส่วนที่ 4 แปลผลค่า BMI ตามเกณฑ์ (จัดย่อหน้าให้อยู่ในบล็อกเดียวกัน)
        if bmi < 18.5:
            st.warning("⚠️ คุณมีน้ำหนักน้อยกว่าเกณฑ์ (ผอม)")
        elif 18.5 <= bmi < 23.0:
            st.success("🎉 คุณมีน้ำหนักอยู่ในเกณฑ์ปกติ (สุขภาพดี)")
        elif 23.0 <= bmi < 25.0:
            st.info("💡 คุณมีน้ำหนักเกินเกณฑ์ (ท้วม)")
        else:
            st.error("🚨 คุณอยู่ในเกณฑ์อ้วน ควรระวังเรื่องสุขภาพและการออกกำลังกาย")
    else:
        st.error("กรุณากรอกส่วนสูงให้ถูกต้อง")

st.divider()
st.write("นางสาวชาลิสา ปันทวัง เลขที่ 4 ม.4/7")
